import { useEffect, type ReactNode } from 'react'

/**
 * Bottom sheet. Closing is handled by the caller (the calendar screen ties
 * sheets to browser history so Android's Back button closes them).
 */
export function Sheet({
  title,
  onClose,
  children,
  footer,
}: {
  title: ReactNode
  onClose: () => void
  children: ReactNode
  footer?: ReactNode
}) {
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => e.key === 'Escape' && onClose()
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [onClose])

  return (
    <div className="fixed inset-0 z-40 flex items-end justify-center" role="dialog" aria-modal="true">
      <button
        type="button"
        aria-label="Close"
        onClick={onClose}
        className="sheet-backdrop absolute inset-0 bg-black/40"
      />
      <div className="sheet-panel relative flex max-h-[92dvh] w-full max-w-lg flex-col rounded-t-2xl bg-surface shadow-xl">
        <div className="mx-auto mt-2 h-1.5 w-10 rounded-full bg-line" aria-hidden="true" />
        <header className="flex items-center gap-2 px-4 pb-2 pt-3">
          <h2 className="min-w-0 flex-1 text-lg font-semibold">{title}</h2>
          <button
            type="button"
            onClick={onClose}
            aria-label="Close"
            className="-mr-2 rounded-full p-2 text-muted active:bg-surface-2"
          >
            <Icon name="close" />
          </button>
        </header>
        <div className="min-h-0 flex-1 overflow-y-auto overscroll-contain px-4 pb-4">{children}</div>
        {footer && (
          <footer className="border-t border-line px-4 pb-[max(env(safe-area-inset-bottom),0.75rem)] pt-3">
            {footer}
          </footer>
        )}
      </div>
    </div>
  )
}

